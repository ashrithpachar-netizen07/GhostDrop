 chk('72-char password ok',await st(reg('ok4@x.io','a1'.repeat(36))),200);
 chk('login email array',await st(a.j('/api/login',J({email:['ok4@x.io'],password:P}))),400);
 chk('login password object',await st(a.j('/api/login',J({email:'ok4@x.io',password:{}}))),400);
