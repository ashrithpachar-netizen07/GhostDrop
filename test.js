// Run: npm test  (spawns its own server on a temp dir)
const {test,before,after}=require('node:test'),assert=require('node:assert'),{spawn}=require('child_process'),os=require('os'),fs=require('fs'),path=require('path');
const D=fs.mkdtempSync(path.join(os.tmpdir(),'gd-')),B='http://localhost:3222',H={'X-Requested-With':'ghostdrop'};
let srv;const J=(b)=>({method:'POST',headers:{...H,'Content-Type':'application/json'},body:JSON.stringify(b)});
const who=()=>{let c='';return{async f(u,o={}){const r=await fetch(B+u,{...o,headers:{...H,...o.headers,cookie:c}});const s=r.headers.getSetCookie?.()[0];if(s)c=s.split(';')[0];return r},j:async function(u,o){const r=await this.f(u,o);return[r.status,await r.json().catch(()=>({}))]}}};
const up=(u,data,name)=>{const f=new FormData();f.append('file',new Blob([data]),name);return u.j('/api/upload',{method:'POST',body:f})};
before(async()=>{srv=spawn('node',['server.js'],{env:{...process.env,PORT:3222,DATA_DIR:D}});await new Promise(r=>setTimeout(r,1500))});
after(()=>srv.kill());
test('full flow + enforcement',async()=>{
 const a=who(),b=who();
 assert.equal((await a.j('/api/me'))[0],401);
 assert.equal((await fetch(B+'/api/register',{method:'POST'})).status,403,'CSRF header required');
 assert.equal((await a.j('/api/register',J({email:'a@x.io',password:'password1'})))[0],200);
 assert.equal((await b.j('/api/register',J({email:'b@x.io',password:'password1'})))[0],200);
 assert.equal((await up(a,'hello','h.txt'))[0],200);
 assert.equal((await up(a,'x','evil.exe'))[0],415,'blocked extension');
 assert.equal((await up(a,'MZ\x90\x00','innocent.txt'))[0],415,'magic-byte exe disguised as txt');
 assert.equal((await up(a,'<html><script>','page.txt'))[0],415,'html disguised');
 assert.equal((await up(a,Buffer.alloc(11*1048576),'big.bin'))[0],413,'size limit');
 const [,l]=await a.j('/api/files/1/links',J({hours:1,maxDl:2,password:'pw123'}));
 const t=l.url.split('/d/')[1];
 assert.equal((await b.j('/api/files/1/links',J({})))[0],404,'other user cannot share my file');
 assert.equal((await b.j('/api/files/1',{method:'DELETE'}))[0],404,'other user cannot delete');
 assert.equal((await a.j('/api/s/nope'))[0],404);
 const dl=(p)=>a.f(`/api/s/${t}/download`,J({password:p}));
 assert.equal((await dl('bad')).status,403);
 const r=await dl('pw123');assert.equal(r.status,200);assert.equal(await r.text(),'hello');
 assert.equal(r.headers.get('content-type'),'application/octet-stream');assert.equal(r.headers.get('x-content-type-options'),'nosniff');
 assert.equal((await dl('pw123')).status,200);
 assert.equal((await dl('pw123')).status,410,'download limit enforced');
 const [,l2]=await a.j('/api/files/1/links',J({hours:1}));const t2=l2.url.split('/d/')[1];
 const [,fl]=await a.j('/api/files');await a.j(`/api/links/${fl[0].links[0].id}/revoke`,{method:'POST',headers:H});
 const [s2,m2]=await a.j('/api/s/'+t2);assert.equal(s2,410);assert.match(m2.error,/revoked/);
 const [,l3]=await a.j('/api/files/1/links',J({hours:1}));const t3=l3.url.split('/d/')[1];
 assert.equal((await a.j('/api/s/'+t3))[0],200);
 await require('@libsql/client').createClient({url:'file:'+path.join(D,'db.sqlite')}).execute('update links set expires=1 where id=3');
 const [s3,m3]=await a.j('/api/s/'+t3);assert.equal(s3,410);assert.match(m3.error,/expired/);
 for(let i=0;i<5;i++)await a.j('/api/login',J({email:'a@x.io',password:'wrong'+i}));
 assert.equal((await a.j('/api/login',J({email:'a@x.io',password:'password1'})))[0],429,'login lockout');
});
